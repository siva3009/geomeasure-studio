"""
Pydantic schemas for GeoMeasure Studio AI Copilot.
"""

from typing import List, Dict, Any, Optional
from uuid import UUID
from pydantic import BaseModel, Field


class AIAssistantRequest(BaseModel):
    """Request payload for AI Copilot analysis."""
    task: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Natural language query or instruction for geospatial analysis.",
        examples=["Calculate all parcel areas and rank the five largest."]
    )
    file_id: Optional[UUID] = Field(
        None,
        description="UUID of the uploaded dataset to analyze. If omitted, ad-hoc geometry may be provided."
    )
    geometry_payload: Optional[Dict[str, Any]] = Field(
        None,
        description="Optional bounded GeoJSON geometry/feature collection for ad-hoc analysis."
    )
    privacy_mode: Optional[str] = Field(
        None,
        description="Optional privacy override: 'standard' or 'local_only'."
    )


class GISFeatureItem(BaseModel):
    """Summary of a measured or validated feature."""
    feature_index: int
    feature_id: Optional[str] = None
    geometry_type: str
    area_sq_meters: Optional[float] = None
    area_hectares: Optional[float] = None
    length_meters: Optional[float] = None
    measurement_crs: Optional[str] = None
    is_valid: bool = True
    validity_reason: Optional[str] = None


class ExportArtifact(BaseModel):
    """Reference to an export artifact generated by the Copilot."""
    format: str = Field(..., description="Export format: 'csv' or 'geojson'")
    filename: str
    record_count: int
    download_url: Optional[str] = None
    content_preview: Optional[str] = None


class ProviderMetadata(BaseModel):
    """Telemetry and execution metadata for the AI provider."""
    provider: str = Field(..., description="Provider name: 'ollama', 'groq', 'openai', or 'deterministic_engine'")
    model: str = Field(..., description="Model identifier used, or 'deterministic-rule-engine'")
    is_local: bool = Field(..., description="Whether inference ran locally without cloud transmission")
    latency_ms: float = Field(..., description="Provider inference time or engine execution time in milliseconds")
    time_to_first_token_ms: Optional[float] = None
    prompt_tokens: Optional[int] = None
    completion_tokens: Optional[int] = None
    total_tokens: Optional[int] = None
    token_usage_estimated: bool = False
    routed_via: Optional[str] = None


class LatencyBreakdown(BaseModel):
    """Detailed timing metrics for the request."""
    total_ms: float
    intent_ms: float = 0.0
    provider_ms: float = 0.0
    tool_execution_ms: float = 0.0


class AIAssistantResponse(BaseModel):
    """Structured response from the AI Copilot."""
    status: str = "completed"
    task: Optional[str] = None
    explanation: str = Field(..., description="Human-readable summary and explanation of findings.")
    intent: str = Field(default="geospatial_inquiry", description="Detected intent or task classification.")
    actions_executed: List[str] = Field(default_factory=list, description="List of GIS tools executed.")
    feature_summary: Optional[Dict[str, Any]] = Field(None, description="Feature counts, types, and dataset bounds.")
    top_features: Optional[List[GISFeatureItem]] = Field(None, description="Top ranked or notable features.")
    highlighted_indices: List[int] = Field(default_factory=list, description="Feature indices to highlight on the map.")
    validation_warnings: List[str] = Field(default_factory=list, description="Geometry validity or CRS warnings.")
    export_artifact: Optional[ExportArtifact] = Field(None, description="Export reference if generated.")
    provider_metadata: ProviderMetadata
    latency_breakdown: LatencyBreakdown
    prompt_tokens: Optional[int] = None
    completion_tokens: Optional[int] = None
    total_tokens: Optional[int] = None


class AIPerformanceStats(BaseModel):
    """Aggregate statistics for AI usage monitoring."""
    total_ai_requests: int
    deterministic_requests: int
    local_provider_requests: int
    hosted_provider_requests: int
    average_latency_ms: float
    total_tokens: int
    errors_count: int
